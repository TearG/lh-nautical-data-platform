with open('questoes.md', 'a', encoding='utf-8') as f:
    f.write('\n## Questão 7.1 - Código Python do Sistema de Recomendação\n')
    f.write('**Código em Python:**\n')
    f.write('```python\n')
    f.write('import pandas as pd\n')
    f.write('from sklearn.metrics.pairwise import cosine_similarity\n\n')
    f.write('# 1. Carregar os datasets\n')
    f.write('orders = pd.read_csv(\'1-lh_nautical_csv/orders.csv\', encoding=\'latin1\')\n')
    f.write('order_items = pd.read_csv(\'1-lh_nautical_csv/order_items.csv\', encoding=\'latin1\')\n')
    f.write('product_variants = pd.read_csv(\'1-lh_nautical_csv/product_variants.csv\', encoding=\'latin1\')\n')
    f.write('products = pd.read_csv(\'1-lh_nautical_csv/products.csv\', encoding=\'latin1\')\n\n')
    f.write('# 2. Construir o dataset unificado\n')
    f.write('merged = orders[[\'id\', \'customer_id\']].merge(order_items[[\'order_id\', \'product_variant_id\']], left_on=\'id\', right_on=\'order_id\')\n')
    f.write('merged = merged.merge(product_variants[[\'id\', \'product_id\']], left_on=\'product_variant_id\', right_on=\'id\')\n')
    f.write('merged = merged.merge(products[[\'id\', \'name\']], left_on=\'product_id\', right_on=\'id\')\n\n')
    f.write('# 3. Construir a Matriz Usuário x Item (Presença/Ausência)\n')
    f.write('user_product = merged.groupby([\'customer_id\', \'product_id\']).size().reset_index()\n')
    f.write('user_product[\'purchased\'] = 1\n')
    f.write('matrix = user_product.pivot(index=\'customer_id\', columns=\'product_id\', values=\'purchased\').fillna(0)\n\n')
    f.write('# 4. Cálculo da Similaridade de Cosseno\n')
    f.write('product_item_matrix = matrix.T\n')
    f.write('similarity_matrix = cosine_similarity(product_item_matrix)\n')
    f.write('similarity_df = pd.DataFrame(similarity_matrix, index=product_item_matrix.index, columns=product_item_matrix.index)\n\n')
    f.write('# 5. Recuperar o ID do Produto Alvo\n')
    f.write('motor = products[products[\'name\'].str.contains(\'Motor de Popa 1949\', na=False, regex=False)]\n')
    f.write('motor_id = motor[\'id\'].values[0]\n\n')
    f.write('# 6. Gerar o Ranking de Similaridade (Desconsiderando ele mesmo)\n')
    f.write('similar_scores = similarity_df[motor_id].sort_values(ascending=False)\n')
    f.write('similar_scores = similar_scores.drop(motor_id)\n')
    f.write('top_5_ids = similar_scores.head(5).index\n\n')
    f.write('print(\"=== TOP 5 RECOMENDAÇÕES PARA \'Motor de Popa 1949\' ===\")\n')
    f.write('for pid in top_5_ids:\n')
    f.write('    pname = products[products[\'id\'] == pid][\'name\'].values[0]\n')
    f.write('    score = similar_scores[pid]\n')
    f.write('    print(f\"Produto: {pname} | Score: {score:.4f}\")\n')
    f.write('```\n')
