with open('questoes.md', 'a', encoding='utf-8') as f:
    f.write('\n## Questão 6.1 - Código Python do Modelo de Previsão\n')
    f.write('**Código em Python:**\n')
    f.write('```python\n')
    f.write('import pandas as pd\n')
    f.write('from sklearn.metrics import mean_absolute_error\n\n')
    f.write('orders = pd.read_csv(\'1-lh_nautical_csv/orders.csv\', encoding=\'latin1\')\n')
    f.write('order_items = pd.read_csv(\'1-lh_nautical_csv/order_items.csv\', encoding=\'latin1\')\n')
    f.write('product_variants = pd.read_csv(\'1-lh_nautical_csv/product_variants.csv\', encoding=\'latin1\')\n')
    f.write('products = pd.read_csv(\'1-lh_nautical_csv/products.csv\', encoding=\'latin1\')\n\n')
    f.write('prod_bussola = products[products[\'name\'].str.contains(\'702\', na=False) & products[\'name\'].str.contains(\'Bordo\', na=False)]\n')
    f.write('prod_bussola = prod_bussola[~prod_bussola[\'name\'].str.contains(\'7024\')]\n\n')
    f.write('bussola_variants = product_variants[product_variants[\'product_id\'].isin(prod_bussola[\'id\'])]\n')
    f.write('bussola_items = order_items[order_items[\'product_variant_id\'].isin(bussola_variants[\'id\'])]\n\n')
    f.write('df_bussola = bussola_items.merge(orders[[\'id\', \'created_at\']], left_on=\'order_id\', right_on=\'id\')\n')
    f.write('df_bussola[\'created_at\'] = pd.to_datetime(df_bussola[\'created_at\'])\n\n')
    f.write('df_bussola[\'year_month\'] = df_bussola[\'created_at\'].dt.to_period(\'M\')\n')
    f.write('monthly_sales = df_bussola.groupby(\'year_month\')[\'quantity\'].sum().reset_index()\n\n')
    f.write('all_months = pd.period_range(start=monthly_sales[\'year_month\'].min(), end=pd.Period(\'2026-03\', \'M\'))\n')
    f.write('monthly_sales = monthly_sales.set_index(\'year_month\').reindex(all_months, fill_value=0).reset_index()\n')
    f.write('monthly_sales.rename(columns={\'index\': \'year_month\'}, inplace=True)\n\n')
    f.write('monthly_sales[\'moving_avg_3m\'] = monthly_sales[\'quantity\'].rolling(window=3).mean().shift(1)\n\n')
    f.write('test_period = monthly_sales[monthly_sales[\'year_month\'].between(pd.Period(\'2026-01\', \'M\'), pd.Period(\'2026-03\', \'M\'))]\n\n')
    f.write('mae = mean_absolute_error(test_period[\'quantity\'], test_period[\'moving_avg_3m\'])\n')
    f.write('print(test_period)\n')
    f.write('print(f\"MAE: {mae:.2f}\")\n')
    f.write('```\n')
